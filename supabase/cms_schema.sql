create table if not exists public.cms_pages (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  nav_label text not null,
  page_title text not null,
  page_description text default '',
  seo_title text default '',
  seo_description text default '',
  hero_title text default '',
  hero_body text default '',
  hero_primary_button_label text default '',
  hero_primary_button_url text default '',
  hero_secondary_button_label text default '',
  hero_secondary_button_url text default '',
  hero_image_url text default '',
  is_published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.cms_sections (
  id uuid primary key default gen_random_uuid(),
  page_id uuid not null references public.cms_pages(id) on delete cascade,
  section_key text not null,
  section_label text not null,
  section_type text not null check (
    section_type in (
      'hero',
      'content',
      'cards',
      'cta',
      'faq',
      'list'
    )
  ),
  title text default '',
  subtitle text default '',
  body text default '',
  image_url text default '',
  primary_button_label text default '',
  primary_button_url text default '',
  secondary_button_label text default '',
  secondary_button_url text default '',
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint cms_sections_page_key_unique unique (page_id, section_key)
);

create table if not exists public.cms_section_items (
  id uuid primary key default gen_random_uuid(),
  section_id uuid not null references public.cms_sections(id) on delete cascade,
  title text not null,
  subtitle text default '',
  body text default '',
  image_url text default '',
  link_label text default '',
  link_url text default '',
  metadata jsonb not null default '{}'::jsonb,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  email text not null unique,
  role text not null default 'editor' check (role in ('admin', 'editor')),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

