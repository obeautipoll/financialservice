-- Financial Services CMS schema for Supabase
-- This model keeps layout/components in React and stores editable content in tables.

create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create table if not exists public.site_settings (
  id bigint generated by default as identity primary key,
  site_name text not null,
  logo_url text default '',
  footer_cta_title text default '',
  footer_cta_body text default '',
  footer_cta_button_label text default '',
  footer_cta_button_url text default '',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint site_settings_single_row check (id = 1)
);

